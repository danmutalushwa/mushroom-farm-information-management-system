const downloadReport = async (req, res, next) => {
    try {
        const report = await ReportHistoryService.getReportById(req.params.id);

        if (!report) {
            return res.status(404).json({
                status: 'fail',
                message: 'Report not found'
            });
        }

        const doc = new PDFDocument({
            margin: 50,
            size: 'A4'
        });

        res.setHeader('Content-Type', 'application/pdf');
        res.setHeader(
            'Content-Disposition',
            `attachment; filename="${report.reportNumber || 'Report'}.pdf"`
        );

        doc.pipe(res);

        // ==========================================
        // HEADER
        // ==========================================

        doc
            .fontSize(22)
            .fillColor('#15803d')
            .text('MUSHROOM FARM INFORMATION MANAGEMENT SYSTEM', {
                align: 'center'
            });

        doc.moveDown(0.5);

        doc
            .fontSize(18)
            .fillColor('black')
            .text(report.title || report.reportType, {
                align: 'center'
            });

        doc.moveDown();

        doc.fontSize(12);

        doc.text(`Report Number : ${report.reportNumber}`);
        doc.text(`Report Type   : ${report.reportType}`);
        doc.text(`Generated By  : ${report.generatedBy?.fullName || 'Administrator'}`);
        doc.text(`Generated On  : ${new Date(report.generatedAt).toLocaleString()}`);

        doc.moveDown();

        // ==========================================
        // SUMMARY
        // ==========================================

        if (report.summary) {

            doc.fontSize(16).text('Summary');

            doc.moveDown(0.5);

            Object.entries(report.summary).forEach(([key, value]) => {

                if (typeof value !== 'object') {
                    doc.fontSize(12).text(
                        `${key.replace(/([A-Z])/g, ' $1')} : ${value}`
                    );
                }

            });

            doc.moveDown();

        }

        // ==========================================
        // PRODUCTION REPORT
        // ==========================================

        if (
            report.reportType === 'Production Report' &&
            report.data?.batches
        ) {

            doc.fontSize(16).text('Production Details');

            doc.moveDown();

            report.data.batches.forEach((batch, index) => {

                doc.fontSize(12).text(`${index + 1}. Batch Number : ${batch.batchNumber}`);
                doc.text(`   Mushroom Type : ${batch.mushroomType}`);
                doc.text(`   Harvest : ${batch.totalHarvest} Kg`);
                doc.text(`   Production Loss : ${batch.productionLoss} Kg`);
                doc.text(`   Status : ${batch.status}`);

                doc.moveDown();

            });

        }

        // ==========================================
        // INVENTORY REPORT
        // ==========================================

        if (
            report.reportType === 'Inventory Report' &&
            report.data?.items
        ) {

            doc.fontSize(16).text('Inventory Items');

            doc.moveDown();

            report.data.items.forEach((item, index) => {

                doc.fontSize(12).text(`${index + 1}. ${item.itemName}`);
                doc.text(`   Item Code : ${item.itemCode}`);
                doc.text(`   Category : ${item.category}`);
                doc.text(`   Quantity : ${item.quantity}`);
                doc.text(`   Stock Status : ${item.stockStatus}`);

                doc.moveDown();

            });

        }

        // ==========================================
        // CUSTOMER REPORT
        // ==========================================

        if (
            report.reportType === 'Customer Report' &&
            report.data?.customers
        ) {

            doc.fontSize(16).text('Customer Details');

            doc.moveDown();

            report.data.customers.forEach((customer, index) => {

                doc.fontSize(12).text(`${index + 1}. ${customer.fullName}`);
                doc.text(`   Customer Code : ${customer.customerCode}`);
                doc.text(`   Phone : ${customer.phoneNumber}`);
                doc.text(`   Customer Type : ${customer.customerType}`);
                doc.text(`   Total Orders : ${customer.totalOrders}`);
                doc.text(`   Total Spent : RWF ${customer.totalSpent}`);
                doc.text(`   Status : ${customer.isActive ? 'Active' : 'Inactive'}`);

                doc.moveDown();

            });

        }

        // ==========================================
        // ORDER REPORT
        // ==========================================

        if (
            report.reportType === 'Order Report' &&
            report.data?.orders
        ) {

            doc.fontSize(16).text('Order Details');

            doc.moveDown();

            report.data.orders.forEach((order, index) => {

                doc.fontSize(12).text(`${index + 1}. ${order.orderNumber}`);
                doc.text(`   Customer : ${order.customerName}`);
                doc.text(`   Phone : ${order.customerPhone}`);
                doc.text(`   Total Items : ${order.totalItems}`);
                doc.text(`   Total Amount : RWF ${order.totalAmount}`);
                doc.text(`   Status : ${order.status}`);
                doc.text(`   Payment Status : ${order.paymentStatus}`);

                doc.moveDown();

            });

        }

        // ==========================================
        // SALES REPORT
        // ==========================================

        if (
            report.reportType === 'Sales Report' &&
            report.data?.sales
        ) {

            doc.fontSize(16).text('Sales Details');

            doc.moveDown();

            report.data.sales.forEach((sale, index) => {

                doc.fontSize(12).text(`${index + 1}. ${sale.saleNumber}`);
                doc.text(`   Customer : ${sale.customerName}`);
                doc.text(`   Total Amount : RWF ${sale.totalAmount}`);
                doc.text(`   Amount Paid : RWF ${sale.amountPaid}`);
                doc.text(`   Payment Status : ${sale.paymentStatus}`);

                doc.moveDown();

            });

        }

        // ==========================================
        // STOCK MOVEMENT REPORT
        // ==========================================

        if (
            report.reportType === 'Stock Movement Report' &&
            report.data?.movements
        ) {

            doc.fontSize(16).text('Stock Movement Details');

            doc.moveDown();

            report.data.movements.forEach((movement, index) => {

                doc.fontSize(12).text(`${index + 1}. ${movement.itemName}`);
                doc.text(`   Item Code : ${movement.itemCode}`);
                doc.text(`   Movement Type : ${movement.movementType}`);
                doc.text(`   Quantity : ${movement.quantity}`);
                doc.text(`   Previous Quantity : ${movement.previousQuantity}`);
                doc.text(`   New Quantity : ${movement.newQuantity}`);
                doc.text(`   Performed By : ${movement.performedBy}`);

                doc.moveDown();

            });

        }

        // ==========================================
        // FINANCIAL SUMMARY
        // ==========================================

        if (report.reportType === 'Financial Report') {

            doc.fontSize(16).text('Financial Report');

            doc.moveDown();

            doc.fontSize(12);
            doc.text(`Total Revenue : RWF ${report.summary?.totalRevenue || 0}`);
            doc.text(`Total Paid : RWF ${report.summary?.totalPaid || 0}`);
            doc.text(`Outstanding Balance : RWF ${report.summary?.outstandingBalance || 0}`);
            doc.text(`Inventory Value : RWF ${report.summary?.inventoryValue || 0}`);

        }

        // ==========================================
        // FOOTER
        // ==========================================

        doc.moveDown(2);

        doc
            .fontSize(10)
            .fillColor('gray')
            .text(
                'Generated automatically by Mushroom Farm Information Management System',
                {
                    align: 'center'
                }
            );

        doc.end();

    } catch (error) {
        logger.error('Download report error:', error.message);
        next(error);
    }
};

const deleteReport = async (req, res) => {
    try {
        const report = await Report.findById(req.params.id);

        if (!report) {
            return res.status(404).json({
                message: "Report not found"
            });
        }

        await Report.findByIdAndDelete(req.params.id);

        res.json({
            message: "Report deleted successfully"
        });

    } catch (error) {
        res.status(500).json({
            message: error.message
        });
    }
};
