const ReportService = require('../services/report.service');
const logger = require('../utils/logger');
const ReportHistoryService = require('../services/reportHistory.service');
const Report = require('../models/report');
const PDFDocument = require('pdfkit');



/**
 * Get Production Report
 */
const getProductionReport = async (req, res, next) => {
    try {
        const { startDate, endDate, mushroomType, status } = req.query;
        
        const report = await ReportService.getProductionReport(
            startDate,
            endDate,
            { mushroomType, status }
        );

        await ReportHistoryService.saveReport({
            reportType: 'Production Report',
            title: 'Production Report',
            description:'Production Report generated by the system',
            parameters: {
                startDate,
                endDate,
                filters: req.query
            },
            data: report,
            summary: report.summary,
            generatedBy: req.user.id
        });
        
        res.status(200).json({
            status: 'success',
            message: 'Production report generated successfully',
            data: report
        });
    } catch (error) {
        logger.error('Get production report error:', error.message);
        next(error);
    }
};

